def plot_turnover(
    universe: str,
    tier: str = "enhanced",
    models: Sequence[str] = ("ridge", "lightgbm", "xgboost"),
    output_dir: Path | None = None,
) -> Path:
    import matplotlib.pyplot as plt

    output_dir = output_dir or FIGURES_DIR
    ensure_dirs()

    cadences = [("daily", 1), ("weekly", 5), ("monthly", 21)]

    records: list[dict] = []
    for cadence, lookback in cadences:
        s = _read_portfolio_summary(universe, None, cadence, lookback)
        if s:
            records.append({"cadence": cadence, "model": "ATC Baseline", "turnover": s.get("ann_turnover", 0)})
        for m in _find_model_tags(universe, cadence, lookback, models, tier=tier):
            s = _read_portfolio_summary(universe, m, cadence, lookback)
            if s:
                records.append({"cadence": cadence, "model": m, "turnover": s.get("ann_turnover", 0)})

    if not records:
        raise FileNotFoundError(f"No portfolio summaries found for {universe}")

    plot_df = pd.DataFrame(records)

    fig, ax = plt.subplots(figsize=(7, 3.5))
    cadence_labels = [c for c, _ in cadences]
    all_models = plot_df["model"].unique().tolist()
    n_models = len(all_models)
    x = np.arange(len(cadence_labels))
    width = 0.8 / n_models

    for i, m in enumerate(all_models):
        vals = []
        for cl in cadence_labels:
            row = plot_df[(plot_df["cadence"] == cl) & (plot_df["model"] == m)]
            vals.append(row["turnover"].values[0] if len(row) > 0 else 0)
        ax.bar(x + i * width, vals, width, label=m)

    ax.set_xticks(x + width * (n_models - 1) / 2)
    ax.set_xticklabels(cadence_labels)
    ax.set_title(f"Annualized Turnover — {universe.upper()} ({tier})")
    ax.set_ylabel("Annual Turnover")
    ax.legend(fontsize=6.5)
    ax.grid(True, alpha=0.3, axis="y")
    fig.tight_layout()

    out = output_dir / f"turnover_{universe}_{tier}.png"
    fig.savefig(out)
    plt.close(fig)
    return out


