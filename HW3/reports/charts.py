def _read_atc_baseline_daily(universe: str, horizon: int = 5) -> pd.DataFrame | None:
    """Read ATCClassifierScore decile L/S daily returns for a universe × horizon."""
    quintile_path = RESULTS_DIR / "quintile" / f"quintile_equity_curves_{universe}.parquet"
    if not quintile_path.exists():
        return None
    qdf = pd.read_parquet(quintile_path)
    key = f"{horizon}d_Total"
    subset = qdf[qdf["_key"] == key].copy()
    if subset.empty:
        return None
    subset = subset.rename(columns={"long_short": "pnl"})
    subset.index.name = "bucket_date"
    subset = subset.reset_index().rename(columns={"bucket_date": "date"})
    subset["date"] = pd.to_datetime(subset["date"])
    return subset[["date", "pnl"]].sort_values("date").dropna()


_PRETTY_UNIVERSE: dict[str, str] = {
    "sp500": "S&P 500", "sp1500": "S&P 1500", "ru3k": "Russell 3000",
}


def plot_atc_baseline_equity(
    universes: Sequence[str] = ("sp500", "sp1500", "ru3k"),
    horizons: Sequence[int] = (1, 3, 5, 10, 20),
    output_dir: Path | None = None,
) -> list[Path]:
    """Dedicated ATCClassifierScore decile L/S cumulative equity curves.

    One chart per universe showing all horizons. No model lines.
    """
    import matplotlib.pyplot as plt

    output_dir = output_dir or FIGURES_DIR
    ensure_dirs()

    horizon_colors = plt.cm.viridis(np.linspace(0.1, 0.9, len(horizons)))
    generated: list[Path] = []

    for univ in universes:
        fig, ax = plt.subplots(figsize=(7.5, 3.8))
        for h, color in zip(horizons, horizon_colors):
            df = _read_atc_baseline_daily(univ, h)
            if df is None:
                continue
            cum = (1 + df["pnl"]).cumprod()
            ax.plot(df["date"], cum, label=f"h={h}d", color=color, linewidth=1.2)

        ax.axhline(y=1.0, color="gray", linestyle="--", linewidth=0.8)
        label = _PRETTY_UNIVERSE.get(univ, univ.upper())
        ax.set_title(f"ATCClassifierScore Decile L/S Cumulative Return — {label}")
        ax.set_xlabel("Date")
        ax.set_ylabel("Cumulative Return")
        ax.legend(loc="upper left", title="Horizon")
        ax.grid(True, alpha=0.3)
        fig.tight_layout()

        out = output_dir / f"atc_baseline_equity_{univ}.png"
        fig.savefig(out)
        plt.close(fig)
        generated.append(out)

    return generated


