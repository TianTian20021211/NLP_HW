def generate_all(
    universe_names: Sequence[str] = ("sp500", "sp1500", "ru3k"),
    tier: str = "enhanced",
    models: Sequence[str] = ("ridge", "lightgbm", "xgboost"),
    cadence: str = "weekly",
    lookback: int = 5,
    output_dir: Path | None = None,
) -> list[Path]:
    set_style()
    output_dir = output_dir or FIGURES_DIR
    ensure_dirs()

    generated: list[Path] = []
    chart_types: list[tuple[str, str]] = [
        ("equity_curves", f"equity_curves_{{}}_{tier}.png"),
        ("ic_heatmap", f"ic_heatmap_{{}}_{tier}.png"),
        ("quintile_spread", f"quintile_spread_{{}}_{tier}.png"),
        ("drawdown", f"drawdown_{{}}_{tier}.png"),
        ("rolling_sharpe", f"rolling_sharpe_{{}}_{tier}.png"),
        ("turnover", f"turnover_{{}}_{tier}.png"),
    ]

    for universe in universe_names:
        for chart_name, expected_fname in chart_types:
            out_path = output_dir / expected_fname.format(universe)
            try:
                if chart_name == "equity_curves":
                    out_path = plot_equity_curves(universe, tier, models, cadence, lookback, output_dir)
                elif chart_name == "ic_heatmap":
                    ic_path = RESULTS_DIR / "ic" / f"ic_summary_{universe}.parquet"
                    if not ic_path.exists():
                        print(f"  SKIP {chart_name} — no IC data for {universe}", file=sys.stderr)
                        continue
                    out_path = plot_ic_heatmap(universe, tier, output_dir)
                elif chart_name == "quintile_spread":
                    qs_path = RESULTS_DIR / "quintile" / f"quintile_summary_{universe}.parquet"
                    if not qs_path.exists():
                        print(f"  SKIP {chart_name} — no quintile data for {universe}", file=sys.stderr)
                        continue
                    out_path = plot_quintile_spread(universe, tier, output_dir)
                elif chart_name == "drawdown":
                    out_path = plot_drawdown(universe, tier, models, cadence, lookback, output_dir)
                elif chart_name == "rolling_sharpe":
                    out_path = plot_rolling_sharpe(universe, tier, models, cadence, lookback, output_dir=output_dir)
                elif chart_name == "turnover":
                    out_path = plot_turnover(universe, tier, models, output_dir)
                generated.append(out_path)
                print(f"  {out_path.name}")
            except FileNotFoundError as e:
                print(f"  SKIP {chart_name} for {universe}: {e}", file=sys.stderr)
            except Exception as e:
                print(f"  FAIL {chart_name} for {universe}: {e}", file=sys.stderr)

    # Dedicated ATC baseline charts (ATCClassifierScore decile, no models)
    print("  --- ATC Baseline charts ---")
    try:
        generated.extend(plot_atc_baseline_equity(universe_names, output_dir=output_dir))
        generated.extend(plot_atc_baseline_drawdown(universe_names, output_dir=output_dir))
        generated.extend(plot_atc_baseline_rolling_sharpe(universe_names, output_dir=output_dir))
        generated.extend(plot_atc_baseline_signaltype_comparison(universe_names, output_dir=output_dir))
    except Exception as e:
        print(f"  FAIL baseline charts: {e}", file=sys.stderr)

    return generated


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate report charts from results/")
    parser.add_argument("--tier", default="enhanced", choices=["enhanced", "stretch", "both"])
    parser.add_argument("--universes", nargs="+", default=["sp500", "sp1500", "ru3k"])
    parser.add_argument("--models", nargs="+", default=["ridge", "lightgbm", "xgboost"])
    parser.add_argument("--cadence", default="weekly")
    parser.add_argument("--lookback", type=int, default=5)
    parser.add_argument("--output-dir", type=Path, default=FIGURES_DIR)
    args = parser.parse_args()

    tiers = ["enhanced", "stretch"] if args.tier == "both" else [args.tier]

    for t in tiers:
        print(f"Charts: tier={t} universes={args.universes}")
        generated = generate_all(
            universe_names=args.universes,
            tier=t,
            models=args.models,
            cadence=args.cadence,
            lookback=args.lookback,
            output_dir=args.output_dir,
        )
        print(f"  Generated {len(generated)} charts -> {args.output_dir}")


if __name__ == "__main__":
    main()
