def set_style() -> None:
    import matplotlib.pyplot as plt

    plt.rcParams.update({
        "font.size": 8,
        "figure.dpi": 150,
        "figure.figsize": (7, 4),
        "axes.prop_cycle": plt.cycler("color", plt.cm.tab10.colors),
        "savefig.bbox": "tight",
        "savefig.pad_inches": 0.1,
    })


def _read_portfolio_daily(
    universe: str,
    tag: str | None,
    cadence: str,
    lookback: int,
) -> pd.DataFrame | None:
    candidates: list[Path]
    if tag:
        candidates = [
            RESULTS_DIR / "portfolio" / f"daily_returns_{universe}_{tag}_{cadence}_{lookback}d.parquet"
        ]
    else:
        candidates = [
            RESULTS_DIR / "portfolio" / f"daily_returns_{universe}_{cadence}_{lookback}d.parquet",
            # Some portfolio runs append cadence twice (e.g. weekly_weekly);
            # this fallback handles a prior naming inconsistency in portfolio output.
            RESULTS_DIR / "portfolio" / f"daily_returns_{universe}_{cadence}_{cadence}_{lookback}d.parquet",
        ]
    path = next((p for p in candidates if p.exists()), None)
    if path is not None:
        df = pd.read_parquet(path)
        df["date"] = pd.to_datetime(df["date"])
        return df.sort_values("date")

    # Fallback: read ATC decile baseline from quintile output.
    # The decile long-short portfolio is generated by backtest/quintile.py
    # and stored under results/quintile/, not results/portfolio/. If the
    # baseline was not also run through backtest/portfolio.py, use this fallback.
    if tag is None:
        quintile_path = RESULTS_DIR / "quintile" / f"quintile_equity_curves_{universe}.parquet"
        if quintile_path.exists():
            qdf = pd.read_parquet(quintile_path)
            key = f"{lookback}d_Total"
            subset = qdf[qdf["_key"] == key].copy()
            if not subset.empty:
                subset = subset.rename(columns={"long_short": "pnl"})
                subset.index.name = "bucket_date"
                subset = subset.reset_index().rename(columns={"bucket_date": "date"})
                subset["date"] = pd.to_datetime(subset["date"])
                return subset[["date", "pnl"]].sort_values("date").dropna()

    return None


def _read_portfolio_summary(
    universe: str,
    tag: str | None,
    cadence: str,
    lookback: int,
) -> dict | None:
    if tag:
        candidates = [
            RESULTS_DIR / "portfolio" / f"summary_{universe}_{tag}_{cadence}_{lookback}d.json"
        ]
    else:
        candidates = [
            RESULTS_DIR / "portfolio" / f"summary_{universe}_{cadence}_{lookback}d.json",
            RESULTS_DIR / "portfolio" / f"summary_{universe}_{cadence}_{cadence}_{lookback}d.json",
        ]
    path = next((p for p in candidates if p.exists()), None)
    if path is None:
        return None
    with open(path) as f:
        return json.load(f)


def _find_model_tags(
    universe: str,
    cadence: str,
    lookback: int,
    models: Sequence[str],
    tier: str | None = None,
) -> list[str]:
    tags: list[str] = []
    portfolio_dir = RESULTS_DIR / "portfolio"
    suffix = f"_{cadence}_{lookback}d"
    for m in models:
        pattern = f"daily_returns_{universe}_{m}*{suffix}.parquet"
        for path in sorted(portfolio_dir.glob(pattern)):
            stem = path.stem
            prefix = f"daily_returns_{universe}_"
            if not stem.startswith(prefix) or not stem.endswith(suffix):
                continue
            tag = stem[len(prefix):-len(suffix)]
            if tier and f"_{tier}" not in tag:
                continue
            if tag not in tags:
                tags.append(tag)
    preferred = [t for t in tags if f"predh{lookback}d" in t]
    return preferred or tags


def plot_equity_curves(
    universe: str,
    tier: str = "enhanced",
    models: Sequence[str] = ("ridge", "lightgbm", "xgboost"),
    cadence: str = "weekly",
    lookback: int = 5,
    output_dir: Path | None = None,
) -> Path:
    import matplotlib.pyplot as plt

    output_dir = output_dir or FIGURES_DIR
    ensure_dirs()

    fig, ax = plt.subplots(figsize=(7.5, 3.8))

    baseline = _read_portfolio_daily(universe, None, cadence, lookback)
    if baseline is not None:
        cum = (1 + baseline["pnl"]).cumprod()
        ax.plot(baseline["date"], cum, label="ATC Baseline", color="black", linewidth=1.5, alpha=0.7)

    colors = plt.cm.tab10.colors
    model_tags = _find_model_tags(universe, cadence, lookback, models, tier=tier)
    for i, tag in enumerate(model_tags):
        df = _read_portfolio_daily(universe, tag, cadence, lookback)
        if df is None:
            continue
        cum = (1 + df["pnl"]).cumprod()
        ax.plot(df["date"], cum, label=tag.capitalize(), color=colors[(i + 1) % 10], linewidth=1.0)

    ax.axhline(y=1.0, color="gray", linestyle="--", linewidth=0.8)
    ax.set_title(f"Cumulative L/S Equity — {universe.upper()} ({tier}, {cadence} {lookback}d)")
    ax.set_xlabel("Date")
    ax.set_ylabel("Cumulative Return")

    if baseline is None and not model_tags:
        plt.close(fig)
        raise FileNotFoundError(f"No portfolio daily returns found for {universe} ({cadence} {lookback}d)")

    ax.legend(loc="upper left")
    ax.grid(True, alpha=0.3)
    fig.tight_layout()

    out = output_dir / f"equity_curves_{universe}_{tier}.png"
    fig.savefig(out)
    plt.close(fig)
    return out


def plot_ic_heatmap(
    universe: str,
    tier: str = "enhanced",
    output_dir: Path | None = None,
) -> Path:
    import matplotlib.pyplot as plt

    output_dir = output_dir or FIGURES_DIR
    ensure_dirs()

    ic_path = RESULTS_DIR / "ic" / f"ic_summary_{universe}.parquet"
    if not ic_path.exists():
        raise FileNotFoundError(f"IC summary not found: {ic_path}")

    ic = pd.read_parquet(ic_path)
    ic_total = ic[ic["signal_type"] == "Total"]
    piv = ic_total.pivot_table(index="feature", columns="horizon", values="mean_ic", aggfunc="mean")

    fig, ax = plt.subplots(figsize=(7, max(4.5, len(piv.index) * 0.3)))
    im = ax.imshow(piv.values, aspect="auto", cmap="RdYlGn", vmin=-0.05, vmax=0.05)
    ax.set_xticks(range(len(piv.columns)))
    ax.set_xticklabels([f"h={c}d" for c in piv.columns], rotation=45, ha="right")
    ax.set_yticks(range(len(piv.index)))
    ax.set_yticklabels(piv.index, fontsize=6.5)
    ax.set_title(f"Mean Spearman IC — {universe.upper()} ({tier}, SignalType=Total)")

    for i in range(len(piv.index)):
        for j in range(len(piv.columns)):
            val = piv.iloc[i, j]
            if not np.isnan(val):
                ax.text(j, i, f"{val:.3f}", ha="center", va="center", fontsize=5.5,
                        color="white" if abs(val) > 0.035 else "black")

    fig.colorbar(im, ax=ax, shrink=0.8, label="Mean IC")
    fig.tight_layout()

    out = output_dir / f"ic_heatmap_{universe}_{tier}.png"
    fig.savefig(out)
    plt.close(fig)
    return out


def plot_quintile_spread(
    universe: str,
    tier: str = "enhanced",
    output_dir: Path | None = None,
) -> Path:
    import matplotlib.pyplot as plt

    output_dir = output_dir or FIGURES_DIR
    ensure_dirs()

    qs_path = RESULTS_DIR / "quintile" / f"quintile_summary_{universe}.parquet"
    if not qs_path.exists():
        raise FileNotFoundError(f"Quintile summary not found: {qs_path}")

    qs = pd.read_parquet(qs_path)
    ls = qs[(qs["leg"] == "long_short") & (qs["signal_type"] == "Total")].copy()

    top_features = (
        ls.groupby("feature")["sharpe"].mean().abs().sort_values(ascending=False).head(8).index.tolist()
    )
    plot_data = ls[ls["feature"].isin(top_features)]

    horizons = sorted(plot_data["horizon"].unique())
    n_horizons = len(horizons)
    n_features = len(top_features)

    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    x = np.arange(n_horizons)
    width = 0.8 / n_features

    for i, feat in enumerate(top_features):
        vals = []
        for h in horizons:
            row = plot_data[(plot_data["feature"] == feat) & (plot_data["horizon"] == h)]
            vals.append(row["sharpe"].values[0] if len(row) > 0 else np.nan)
        ax.bar(x + i * width, vals, width, label=feat[:35])

    ax.set_xticks(x + width * (n_features - 1) / 2)
    ax.set_xticklabels([f"h={h}d" for h in horizons])
    ax.set_title(f"L/S Quintile Sharpe by Feature — {universe.upper()} ({tier}, SignalType=Total)")
    ax.set_ylabel("Sharpe Ratio")
    ax.legend(loc="lower left", fontsize=6, ncol=2)
    ax.axhline(y=0, color="gray", linewidth=0.5)
    ax.grid(True, alpha=0.3, axis="y")
    fig.tight_layout()

    out = output_dir / f"quintile_spread_{universe}_{tier}.png"
    fig.savefig(out)
    plt.close(fig)
    return out


